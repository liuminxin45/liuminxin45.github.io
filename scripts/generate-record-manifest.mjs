import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  dateFromFile,
  excerptFromMarkdown,
  markdownToHtml,
  parseFrontmatter,
  slugFromFile,
  sortKey,
} from './markdown-utils.mjs'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const recordsDir = path.join(rootDir, 'public', 'records')
const outputFile = path.join(rootDir, 'src', 'data', 'records.generated.ts')

function collectMarkdown(dir, base = '') {
  let files = []

  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) {
      continue
    }

    const absolute = path.join(dir, name)
    const relative = path.join(base, name)
    const stats = statSync(absolute)

    if (stats.isDirectory()) {
      files = files.concat(collectMarkdown(absolute, relative))
      continue
    }

    if (stats.isFile() && path.extname(name).toLowerCase() === '.md') {
      files.push(relative.replaceAll(path.sep, '/'))
    }
  }

  return files.sort((a, b) => a.localeCompare(b, 'zh-CN'))
}

function titleFromFile(file) {
  return path
    .basename(file, path.extname(file))
    .replace(/^\d{4}[-_.]\d{2}[-_.]\d{2}[-_\s]*/, '')
    .replace(/[-_]+/g, ' ')
    .trim()
}

mkdirSync(recordsDir, { recursive: true })
mkdirSync(path.dirname(outputFile), { recursive: true })

const records = collectMarkdown(recordsDir).map(file => {
  const absolute = path.join(recordsDir, file)
  const raw = readFileSync(absolute, 'utf8')
  const article = parseFrontmatter(raw)
  const slug = article.data.slug || slugFromFile(file)
  const date = article.data.date || dateFromFile(file)
  const assetDir = path.posix.dirname(file)
  const assetBase = assetDir === '.' ? 'records' : `records/${assetDir}`
  const cover = article.data.cover
    ? `${assetBase}/${article.data.cover.replace(/^\.\//, '')}`
    : ''

  return {
    file,
    slug,
    title: article.data.title || titleFromFile(file),
    date,
    category: article.data.category || '记录',
    excerpt: article.data.excerpt || excerptFromMarkdown(article.body),
    cover,
    alt: article.data.alt || article.data.title || titleFromFile(file),
    contentHtml: markdownToHtml(article.body, { assetBase }),
    sortKey: sortKey(date, file),
  }
}).sort((a, b) => b.sortKey.localeCompare(a.sortKey) || b.file.localeCompare(a.file, 'zh-CN'))

const output = `// This file is generated by scripts/generate-record-manifest.mjs.
// Do not edit it manually. Add records to public/records instead.

export type RecordItem = {
  file: string
  slug: string
  title: string
  date: string
  category: string
  excerpt: string
  cover: string
  alt: string
  contentHtml: string
  sortKey: string
}

export const records: RecordItem[] = ${JSON.stringify(records, null, 2)}
`

writeFileSync(outputFile, output)
console.log(`[records] generated ${records.length} record(s)`)
